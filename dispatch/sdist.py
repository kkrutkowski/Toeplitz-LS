"""Assemble the source distribution.

The sdist is not a copy of the repository: it is a staged tree that installs
with ``pip install toeplitz_ls-<version>.tar.gz`` and nothing else.  It carries
the C sources, the Python package and a small PEP 517 backend
(:mod:`dispatch.sdist_backend`, copied in as ``tls_source_build.py``) that
compiles the baseline library at install time.

That is the fallback path -- every platform the project supports ships a wheel,
which is what pip will normally choose.  Wheels-only would also be a valid
release, but a source tree that compiles on the host is the difference between
"this platform is unsupported" and "this platform needs a compiler".
"""

from __future__ import annotations

import gzip
import json
import os
import shutil
import tarfile
from pathlib import Path

from . import project as P
from . import variants as V

ROOT = V.repo_root()
BUILD = ROOT / ".build"
DIST = ROOT / "dist"
PACKAGE = ROOT / "toeplitz-ls" / "toeplitz_ls"
BACKEND = Path(__file__).resolve().parent / "sdist_backend.py"

# What the archive ships: the package, the sources the generic build compiles,
# the headers they include, and the backend.  Tests, the dispatch machinery and
# the LUT generators stay in the repository.
PACKAGE_FILES = ("__init__.py", "_dispatch.py", "_fastchi2.py", "_ihs.py", "utils.py")
SOURCES = ("nanofft.c", "nufft1.c", "linalg.c", "chi2per.c", "utils.c", "tuning.c", "cpu_features.c", "probe_arm64.c")


def _toml_string(value: str) -> str:
    # TOML basic strings escape like JSON, so this is safe for names, versions
    # and single-line descriptions.
    return json.dumps(str(value))


def pyproject(version: str) -> str:
    """The pyproject.toml of the archive: metadata plus the source backend."""
    proj = P.project()
    lines = [
        "# Generated by dispatch.sdist -- edit toeplitz-ls/pyproject.toml instead.",
        "[build-system]",
        "requires = []",
        'build-backend = "tls_source_build"',
        'backend-path = ["."]',
        "",
        "[project]",
        "name = %s" % _toml_string(proj["name"]),
        "version = %s" % _toml_string(version),
    ]
    if proj.get("description"):
        lines.append("description = %s" % _toml_string(" ".join(str(proj["description"]).split())))
    lines += ['readme = "README.md"', "license = { text = %s }" % _toml_string(P.license_id())]
    if proj.get("requires-python"):
        lines.append("requires-python = %s" % _toml_string(proj["requires-python"]))
    dependencies = proj.get("dependencies", [])
    lines.append("dependencies = [%s]" % ", ".join(_toml_string(dep) for dep in dependencies))
    optional = proj.get("optional-dependencies") or {}
    if optional:
        lines.append("")
        lines.append("[project.optional-dependencies]")
        for extra, dependencies in optional.items():
            lines.append("%s = [%s]" % (_toml_string(extra), ", ".join(_toml_string(dep) for dep in dependencies)))
    lines.append("")
    return "\n".join(lines)


def stage(version: str) -> Path:
    """Write the archive tree under .build/sdist/ and return its root."""
    root_name = "toeplitz_ls-%s" % version
    staging = BUILD / "sdist" / root_name
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)

    (staging / "PKG-INFO").write_text(P.metadata(version), encoding="utf-8")
    shutil.copyfile(P.README, staging / "README.md")
    shutil.copyfile(P.LICENSE, staging / "LICENSE")
    (staging / "pyproject.toml").write_text(pyproject(version), encoding="utf-8")
    shutil.copyfile(BACKEND, staging / "tls_source_build.py")

    (staging / "toeplitz_ls").mkdir()
    for name in PACKAGE_FILES:
        shutil.copyfile(PACKAGE / name, staging / "toeplitz_ls" / name)

    (staging / "src").mkdir()
    for name in SOURCES:
        shutil.copyfile(ROOT / "src" / name, staging / "src" / name)

    (staging / "include").mkdir()
    for header in sorted((ROOT / "include").glob("*.h")):
        shutil.copyfile(header, staging / "include" / header.name)

    return staging


# One timestamp for every member, so two runs over identical sources produce
# byte-identical archives.  315532800 is 1980-01-01, the oldest date a ZIP or
# tar reader is guaranteed to accept.
EPOCH = int(os.environ.get("SOURCE_DATE_EPOCH", "315532800"))


def _clean(info: tarfile.TarInfo) -> tarfile.TarInfo:
    info.uid = info.gid = 0
    info.uname = info.gname = ""
    info.mtime = EPOCH
    info.mode = 0o755 if info.isdir() else 0o644
    return info


def tarball(staging: Path) -> Path:
    DIST.mkdir(exist_ok=True)
    out = DIST / ("%s.tar.gz" % staging.name)
    # gzip records a timestamp in its header; pinning it keeps reruns identical.
    with open(out, "wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
                archive.add(staging, arcname=staging.name, filter=_clean, recursive=True)
    return out


def main(argv=None) -> int:
    version = P.version()
    staging = stage(version)
    out = tarball(staging)
    print("[sdist] %s (%.1f KiB)" % (out, out.stat().st_size / 1024.0))
    for path in sorted(staging.rglob("*")):
        if path.is_file():
            print("  %s" % path.relative_to(staging))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
